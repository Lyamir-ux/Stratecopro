/** Classeur SheetJS équivalent au fichier téléversé (valeurs mises en cache + formules). */
export function makeClasseurDornach(): WorkBook {
  const ws: WorkSheet = {};
  for (const [adresse, valeur, formule] of CELLULES) {
    const cell: CellObject =
      typeof valeur === "number" ? { t: "n", v: valeur } : valeur == null ? { t: "n", v: 0 } : { t: "s", v: valeur };
    if (formule) cell.f = formule;
    ws[adresse] = cell;
  }
  ws["!ref"] = "A1:I118";
  ws["!merges"] = FUSIONS.map((r) => utils.decode_range(r));
  const wb = utils.book_new();
  utils.book_append_sheet(wb, ws, "PF estimatif");
  return wb;
}
