export function makeClasseurGareEstimatif(): WorkBook {
  const ws: WorkSheet = {};
  for (const [adresse, v, f] of CELLULES) {
    const cell: CellObject = typeof v === "number" ? { t: "n", v } : { t: "s", v: v ?? "" };
    if (f) cell.f = f;
    ws[adresse] = cell;
  }
  ws["!ref"] = "A1:H131";
  const wb = utils.book_new();
  utils.book_append_sheet(wb, ws, "PF estimatif - 9, rue de la gar");
  return wb;
}
